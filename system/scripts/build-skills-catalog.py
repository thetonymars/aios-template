"""Build system/skills/skills.md from the header of each skill.

One source of truth: the header (frontmatter) of each skill's SKILL.md, or of
its CONTEXT.md when a bundle has no SKILL.md at its root. The catalog is built
from it and is never edited by hand.

usage (from the root of the AIOS folder):
  python3 -I system/scripts/build-skills-catalog.py .           # write skills.md
  python3 -I system/scripts/build-skills-catalog.py . --check   # exit 1 if skills.md is out of date
  python3 -I system/scripts/build-skills-catalog.py . --stdout  # print, write nothing

Header fields read:
  name, description  - always
  summary            - optional: the catalog line, when the cut description reads badly
  asleep             - optional: reason text; the skill goes to «Asleep», not offered
  mode / type        - «bundle» / «skill-bundle» marks a bundle

Safety:
  - A skill file that iCloud has not downloaded yet (.SKILL.md.icloud) stops the
    run before anything is written: the catalog would silently lose that skill.
    The script asks macOS to download it (brctl) and waits a little first.
  - The catalog is written whole or not at all (temp file, then rename).
  - Tests: python3 -I system/scripts/tests/test_build_skills_catalog.py
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

MAX_WORDS = 30
ENTRY_FILES = ("SKILL.md", "CONTEXT.md")
SKIP_DIRS = {"node_modules", ".git", "__pycache__", ".venv", "venv"}

HEADER = """# Skills Catalog

> Built by `system/scripts/build-skills-catalog.py` from the header of each skill's `SKILL.md`. Do not edit this file by hand: change the skill's header, then run the script.
> Find the skill here, then open its `SKILL.md`: the full description and how to run it are there. Version and source of a skill are in its header.
> Personal settings for skills (accounts, preferences) live in one file, `skill-settings.md`, next to this one: a `## <skill>` section per skill. Skills never hold personal data themselves.

## Quick reference

"""

ASLEEP_HEADER = """
## Asleep — not offered

Skills switched off by the person. Do not run or suggest them. To wake one: remove the `asleep:` field from its header and the notice from its `SKILL.md`, then run the script.

"""


class NotDownloaded(Exception):
    pass


def warn(msg):
    print(f"warning: {msg}", file=sys.stderr)


def read_text(path):
    raw = open(path, "rb").read()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        warn(f"{path}: not UTF-8 — read with replaced characters; save it as UTF-8")
        text = raw.decode("utf-8-sig", errors="replace")
    return text.replace("\r\n", "\n").replace("\r", "\n")


def unquote(val):
    if len(val) >= 2 and val[0] == '"' and val[-1] == '"':
        return re.sub(r'\\(["\\])', r"\1", val[1:-1])
    if len(val) >= 2 and val[0] == "'" and val[-1] == "'":
        return val[1:-1].replace("''", "'")
    return val


def finish(first, cont):
    parts = ([first] if first else []) + [c for c in cont if c]
    return " ".join(parts).strip()


def frontmatter(text):
    """A small reader for the flat YAML header skills use: key: value, quoted
    strings, block scalars (| > |- >-) and plain values that go on over indented lines."""
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end < 0:
        return {}
    out, key, cont, block = {}, None, [], False
    for line in text[3:end].split("\n"):
        indented = line[:1] in (" ", "\t")
        if key is not None and (indented or (block and not line.strip())):
            cont.append(line.strip())
            continue
        if key is not None:
            out[key] = finish(out[key], cont)
            key = None
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_-]*):\s*(.*)$", line)
        if not m:
            continue
        k, val = m.group(1), m.group(2).strip()
        block = val in ("|", ">", "|-", ">-", "|+", ">+")
        out[k] = "" if block else val
        key, cont = k, []
    if key is not None:
        out[key] = finish(out[key], cont)
    return {k: unquote(v) for k, v in out.items()}


def clean(s):
    return re.sub(r"\s+", " ", s or "").strip()


def short(desc):
    """The catalog line: the description's first sentence, cut before its details."""
    d = clean(desc)
    if re.match(r"(?i)use (when|for)\b", d):
        first = re.split(r"(?<=[.!?])\s", d)[0]
    else:
        first = re.split(r"(?<=[.!?])\s+(?=[A-ZА-ЯІЇЄҐ\"'«])|\s+Use when|\s+Use this|\s+Use for|\s+Triggers?:", d)[0]
        for sep in (" — ", ": "):
            i = first.find(sep)
            if i > 0 and len(first[:i].split()) >= 6:
                first = first[:i]
                break
    words = first.rstrip(" .").split()
    if not words:
        return ""
    if len(words) > MAX_WORDS:
        return " ".join(words[:MAX_WORDS]) + " …"
    return " ".join(words) + "."


def native_triggers(desc, limit=3):
    """Up to three trigger phrases in Cyrillic: the words the person really types.
    A quote closes only before a comma, dot, semicolon, bracket or the end — so an
    apostrophe inside a word («п'ятниця») does not cut the phrase."""
    m = re.search(r"Triggers?:(.*)$", desc, re.S)
    if not m:
        return []
    found = re.findall(r"""(['"«])(.+?)(?:\1|»)(?=\s*(?:[,.;)]|$))""", m.group(1).strip())
    said = [clean(x[1]) for x in found]
    return [x for x in said if re.search(r"[А-Яа-яІіЇїЄєҐґ]", x) and len(x) <= 60][:limit]


def is_bundle(folder, fm, depth=3):
    if fm.get("mode") == "bundle" or fm.get("type") == "skill-bundle":
        return True
    base = folder.rstrip(os.sep).count(os.sep)
    for root, dirs, files in os.walk(folder):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".")]
        if root.count(os.sep) - base >= depth:
            dirs[:] = []
        if root != folder and "SKILL.md" in files:
            return True
    return False


def placeholders(folder):
    return [os.path.join(folder, f".{name}.icloud") for name in ENTRY_FILES
            if os.path.exists(os.path.join(folder, f".{name}.icloud"))
            and not os.path.exists(os.path.join(folder, name))]


def download(paths, wait=30):
    """Ask iCloud to download evicted files; True when all arrived."""
    if not shutil.which("brctl"):
        return False
    for p in paths:
        subprocess.run(["brctl", "download", p], capture_output=True)
    deadline = time.time() + wait
    while time.time() < deadline:
        if all(not os.path.exists(p) for p in paths):
            return True
        time.sleep(1)
    return False


def build(vault, wait=30):
    skills_dir = os.path.join(vault, "system", "skills")
    if not os.path.isdir(skills_dir):
        raise SystemExit(f"no folder {skills_dir}: give the vault root as the argument")
    folders = [s for s in sorted(os.listdir(skills_dir))
               if os.path.isdir(os.path.join(skills_dir, s)) and not s.startswith((".", "_"))]
    evicted = [p for s in folders for p in placeholders(os.path.join(skills_dir, s))]
    if evicted and not download(evicted, wait):
        raise NotDownloaded(evicted)
    awake, asleep = [], []
    for slug in folders:
        folder = os.path.join(skills_dir, slug)
        entry = next((os.path.join(folder, f) for f in ENTRY_FILES
                      if os.path.isfile(os.path.join(folder, f))), None)
        if not entry:
            warn(f"{slug}: no SKILL.md or CONTEXT.md — left out of the catalog")
            continue
        fm = frontmatter(read_text(entry))
        if not clean(fm.get("description")):
            warn(f"{slug}: {os.path.basename(entry)} has no header with a description — left out of the catalog")
            continue
        marks = []
        if is_bundle(folder, fm):
            marks.append("bundle")
        name = clean(fm.get("name")) or slug
        if name not in (slug, f"{slug}-suite"):
            marks.append(f"name inside: `{name}`")
        mark = f" ({'; '.join(marks)})" if marks else ""
        line = clean(fm.get("summary")) or short(fm["description"])
        said = native_triggers(fm["description"])
        if said:
            line += " Said as: " + ", ".join(f"«{x}»" for x in said) + "."
        if clean(fm.get("asleep")):
            asleep.append(f"- **{slug}** — asleep: {clean(fm['asleep'])}\n")
        else:
            awake.append(f"- **{slug}**{mark}: {line}\n")
    text = HEADER + "".join(awake)
    if asleep:
        text += ASLEEP_HEADER + "".join(asleep)
    return text, len(awake), len(asleep)


def write_whole(target, text):
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(target), prefix=".skills-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, target)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)


def main():
    # A Windows console is often cp1252: a path or a word in Cyrillic would stop the script.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    vault = args[0] if args else "."
    target = os.path.join(vault, "system", "skills", "skills.md")
    try:
        text, n_awake, n_asleep = build(vault)
    except NotDownloaded as e:
        print("stopped, nothing written: iCloud has not downloaded these files yet:", file=sys.stderr)
        for p in e.args[0]:
            print(f"  {p}", file=sys.stderr)
        print("run `brctl download <file>` for each, wait, then run the script again", file=sys.stderr)
        sys.exit(2)
    if "--check" in sys.argv:
        current = read_text(target) if os.path.exists(target) else ""
        if current != text:
            print("skills.md is out of date: run python3 -I system/scripts/build-skills-catalog.py .")
            sys.exit(1)
        print("skills.md is up to date")
        return
    if "--stdout" in sys.argv:
        sys.stdout.write(text)
        return
    write_whole(target, text)
    print(f"wrote {target}: {n_awake} skills, {n_asleep} asleep")


if __name__ == "__main__":
    main()
